/**
 * Filter personas matching a given language code
 */
export function getPersonasForLanguage(langCode: LanguageCode): CelebrityVoicePersona[] {
  const norm = langCode === 'hinglish' ? 'hi' : langCode;
  return CELEBRITY_VOICE_PERSONAS.filter((p) => p.languageCode === norm);
}

/**
 * Look up a persona by unique ID
 */
export function getPersonaById(id?: string): CelebrityVoicePersona | undefined {
  if (!id) return undefined;
  return CELEBRITY_VOICE_PERSONAS.find((p) => p.id === id);
}
